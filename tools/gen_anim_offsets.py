#!/usr/bin/env python3
"""
gen_anim_offsets.py - write include/port/anim_offsets.h from the decomp's
assets/animationtable_data.h.

On N64 the animation header segment is linked at address 0, so the
address of a label such as ANIM_DATA_idle *is* its offset into the
animation table, and game code uses it that way:

    &ptr_animation_table->data[(s32)&ANIM_DATA_idle]

On the port those labels would be real addresses. The generated header
redefines each one as

    #define ANIM_DATA_idle (*(s32 *)PTR_ANIM_idle)

so &ANIM_DATA_idle is the constant offset again (&* cancels without a
read, and there is no relocation for 3dsxtool to reject).

    python tools/gen_anim_offsets.py [<decomp dir>]
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def main():
    decomp = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "external" / "goldeneye"
    header = (decomp / "assets" / "animationtable_data.h").read_text()
    offsets = dict(re.findall(r"#define PTR_ANIM_(\w+) (0x[0-9A-Fa-f]+)", header))
    names = re.findall(r"extern s32 ANIM_DATA_(\w+);", header)

    out = [
        "/*",
        " * anim_offsets.h - ANIM_DATA_* labels as offsets into the animation",
        " * table, the way the N64 link (segment at address 0) made them.",
        " * Generated by tools/gen_anim_offsets.py; included at the end of the",
        " * decomp's assets/animationtable_data.h under TARGET_3DS.",
        " */",
        "#ifndef PORT_ANIM_OFFSETS_H",
        "#define PORT_ANIM_OFFSETS_H",
        "",
        "#define ANIM_DATA_empty (*(s32 *)0)",
    ]
    skipped = []
    for n in names:
        if n in offsets:
            out.append(f"#define ANIM_DATA_{n} (*(s32 *)PTR_ANIM_{n})")
        else:
            skipped.append(n)
    out += ["", "#endif /* PORT_ANIM_OFFSETS_H */", ""]
    path = ROOT / "include" / "port" / "anim_offsets.h"
    path.write_text("\n".join(out), newline="\n")
    print(f"wrote {path} ({len(names) - len(skipped)} labels; no offset for: {', '.join(skipped)})")


if __name__ == "__main__":
    main()
